const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {JSDOM}=require('jsdom');
const html=fs.readFileSync('index.html','utf8');
const dom=new JSDOM(html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/g,''),{url:'https://justinneal907-gif.github.io/CLM-CRM/',runScripts:'outside-only'});
const ctx=dom.getInternalVMContext();ctx.structuredClone=structuredClone;ctx.console=console;
vm.runInContext(fs.readFileSync('assets/crm-bridal-materials.js','utf8'),ctx);
const script=html.match(/<script>([\s\S]*?)<\/script>/)[1];
vm.runInContext(script.slice(0,script.indexOf('bootstrapWorkspace();')),ctx);
const run=s=>vm.runInContext(s,ctx),read=s=>JSON.parse(run(`JSON.stringify(${s})`));

run(`db={models:[{id:'m',name:'Model',description:'Saved description',photo:'https://test/primary.jpg',portfolioPhotos:['https://test/portfolio.jpg',{url:'https://test/library.jpg'}],textOptions:[{id:'saved',label:'Saved text',text:'My saved text'}]}],contacts:[],drafts:[{id:'other',photoSelections:{m:['https://test/other-package.jpg']}}],draft:{modelIds:[],photoSelections:{},previewHtml:'<div><p>Keep my opening</p><p>Thank you,</p></div>'},selected:[],photoLibrary:{m:[{url:'https://test/library.jpg'},{url:'https://test/deleted.jpg'}]},deletedPhotoKeys:{m:[photoKey('https://test/deleted.jpg')]},settings:{}};selected=[];
persistWorkspaceSafe=async()=>true;renderAll=()=>{};renderEmailMatches=()=>{};
document.querySelector('#includePhotos').checked=true;
addToEmail('m');`);
assert.deepEqual(read('draftPhotosForModel(db.models[0])'),['https://test/library.jpg','https://test/portfolio.jpg','https://test/primary.jpg']);
assert.match(read('db.draft.previewHtml'),/My saved text/);
assert.match(read('db.draft.previewHtml'),/portfolio.jpg/);
assert.match(read('db.draft.previewHtml'),/Keep my opening/);
assert.ok(!read('db.draft.previewHtml').includes('other-package'));
run('db=JSON.parse(JSON.stringify(db))');
assert.equal(read('draftPhotosForModel(db.models[0]).length'),3);
assert.equal(read('draftModelExtra(db.models[0]).textOptionId'),'saved');
run("db.models[0].textOptions[0].text='Updated saved text'");
assert.equal(read('draftModelExtra(db.models[0]).text'),'Updated saved text');
run("db.draft.userOverrides={photoSelections:{m:[]},modelExtras:{m:{text:'',enabled:false}}}");
assert.deepEqual(read('draftPhotosForModel(db.models[0])'),[]);
assert.equal(read('draftModelExtra(db.models[0]).enabled'),false);
run("db.draft.userOverrides={photoSelections:{m:['https://test/chosen.jpg']},modelExtras:{m:{text:'Package text',enabled:true}}}");
assert.deepEqual(read('draftPhotosForModel(db.models[0])'),['https://test/chosen.jpg']);
assert.equal(read('draftModelExtra(db.models[0]).text'),'Package text');
run("db.draft={};db.drafts=[];delete db.models[0].textOptions");
assert.equal(read('draftModelExtra(db.models[0]).enabled'),true);
assert.equal(read('draftModelExtra(db.models[0]).text'),'Saved description');
console.log('PASS: insertion includes saved gallery/text, reload, option edits, description, deletion, exact package overrides and cross-package isolation.');
dom.window.close();
