const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const script = fs.readFileSync(require('node:path').join(__dirname, '../index.html'), 'utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
const context = { structuredClone, console, Intl, localStorage: { getItem: () => null, setItem() {} }, document: { querySelector: () => null } };
vm.createContext(context);
vm.runInContext(script.slice(0, script.indexOf('initNav();setupFilters();hydrateDraft();renderAll();')), context);
const run = code => JSON.parse(vm.runInContext(`JSON.stringify(${code})`, context));
const seeds = run('[...MILAN_FIRST_DAY_DRAFTS,...MILAN_REST_DRAFTS]');
assert.equal(seeds.length, 61);
assert.ok(seeds.every(d => d.models.length && d.models.length === d.modelIds.length));
assert.ok(run('[...MILAN_FIRST_DAY_DRAFTS,...MILAN_REST_DRAFTS].every(d=>d.modelIds.every(id=>!isMilanUnavailable(id,seed.models))&&d.models.every(n=>!isMilanUnavailable(n,seed.models)))'));
vm.runInContext(`
const blockedIds=[...MILAN_SS27_UNAVAILABLE_IDS];
const keep='new-york-women-agang';
const oldDraft={id:'milan-ss27-day1-dhruv-kapoor',subject:'Edited subject',brandProject:'Milan Fashion Week S/S 2027',modelIds:[keep,...blockedIds],models:['Agang','Seven Wright','Molly','Mobee','Mobée','Hadiyah Lawal','Anastasia','Ni Simone','Fianna','Ann-Neika','Tinin','Victoria'],photoSelections:{[keep]:'keep.jpg',[blockedIds[0]]:'remove.jpg'},html:'<div><b>Seven</b><img src="seven.jpg"></div>',notes:'Private notes',recipientEmail:'saved@example.test',brief:'Personal wording',packageLink:'https://example.test/package'};
const unaffected={id:'nyfw-draft',brandProject:'NYFW S/S 2027',modelIds:[...blockedIds],models:['Seven'],html:'<b>Seven</b>',photoSelections:{[blockedIds[0]]:'keep-outside-milan.jpg'}};
const future={...unaffected,id:'future',brandProject:'Milan Fashion Week S/S 2028'};
const historical={id:'sent-record',models:['Seven'],modelIds:[blockedIds[0]],status:'Submitted'};
const workspace={...structuredClone(seed),recovery:{milanPackageDepthVersion:1,milanOpenCloseVersion:1},drafts:[oldDraft,unaffected,future],draft:{...oldDraft},activeDraftId:oldDraft.id,selected:[keep,...blockedIds],submissions:[historical],bookings:[{id:'booking',model:'Seven'}],tasks:[{id:'task',task:'Keep'}],customPhotos:{[blockedIds[0]]:'preserved.jpg'}};
const migrated=applyRecovered(workspace);
`, context);
const result = run('migrated');
const original = run('workspace');
const cleaned = result.drafts.find(d => d.id === original.draft.id);
assert.deepEqual(cleaned.modelIds, ['new-york-women-agang']);
assert.deepEqual(cleaned.models, ['Agang']);
assert.deepEqual(cleaned.photoSelections, { 'new-york-women-agang': 'keep.jpg' });
assert.equal(cleaned.html, '');
for (const key of ['notes','recipientEmail','brief','packageLink']) assert.equal(cleaned[key], original.draft[key]);
assert.deepEqual(result.selected, ['new-york-women-agang']);
assert.deepEqual(result.draft.modelIds, ['new-york-women-agang']);
for (const id of ['nyfw-draft','future']) assert.deepEqual(result.drafts.find(d => d.id === id), original.drafts.find(d => d.id === id));
for (const key of ['models','bookings','tasks','customPhotos']) assert.deepEqual(result[key], original[key]);
assert.deepEqual(result.submissions.find(d => d.id === 'sent-record'), original.submissions[0]);
assert.deepEqual(run('applyRecovered(migrated)'), result);
assert.ok(run("['Ann Neika','Ann-Neika','Fianna McHale','Mobée','Mobee','Ni Simone','Victoria Sepiashvili'].every(name=>isMilanUnavailable({id:'custom',name}))"));
const cachedOnly = run("cleanMilanDraft({brandProject:'Milan Fashion Week S/S 2027',html:'<b>Seven Wright</b>'},seed.models)");
assert.equal(cachedOnly.html, '');
console.log('PASS: 61 Milan packages; all 10 models and 13 board IDs excluded; saved/active drafts migrated; roster, sent records and unrelated drafts preserved; repeat load stable.');
